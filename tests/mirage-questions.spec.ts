import { test, expect } from '@playwright/test';

test('documented-style forms use concrete choices and expose full scan output', async ({ page }) => {
  test.setTimeout(180_000);
  await page.goto('experiments/mirage/');
  await expect(page.locator('#ask')).toBeDisabled();
  await page.locator('[data-sample="desk"]').click();
  await expect(page.locator('#question')).toHaveValue('object');
  await expect(page.locator('#choices')).toHaveValue('cup, pen, laptop, elephant');
  await expect(page.locator('[data-answer]')).toHaveCount(5);
  await page.locator('#action').click();
  await expect(page.locator('#status')).toHaveText('Ready', { timeout: 120_000 });
  await page.locator('#action').click();
  await expect(page.locator('#ask')).toBeEnabled({ timeout: 120_000 });
  const record = JSON.parse(await page.locator('#scene-output').textContent() || '{}');
  expect(record.objects.length).toBeGreaterThan(0);
  const requests: string[] = [];
  page.on('request', r => requests.push(r.url()));
  await page.locator('#ask').click();
  await expect(page.locator('#answer-status')).toContainText('Which of these objects can you see?', { timeout: 120_000 });
  await expect(page.locator('[data-answer].selected')).toHaveCount(1);
  await expect(page.locator('#probability-labels')).toContainText('Abstain');
  expect(requests).toEqual([]);
  await page.locator('#question').selectOption('document');
  await expect(page.locator('#choices')).toHaveValue('receipt, menu, letter');
  await page.locator('#question').selectOption('object');
  await page.locator('#choices').fill('cup');
  await expect(page.locator('#ask')).toBeDisabled();
  await expect(page.locator('[data-answer].selected')).toHaveCount(0);
  await page.locator('[data-sample="parking"]').click();
  await expect(page.locator('#question')).toHaveValue('sign');
  await expect(page.locator('#ask')).toBeDisabled();
  await expect(page.locator('#scene-output')).toContainText('Scan an image');
  await page.locator('#file').setInputFiles('public/experiments/mirage/samples/desk.jpg');
  await expect(page.locator('#mark')).toHaveAttribute('aria-label', 'Your image');
  await page.locator('#question').selectOption('object');
  await page.locator('#action').click();
  await expect(page.locator('#ask')).toBeEnabled({timeout:120_000});
  await page.locator('#ask').click();
  await expect(page.locator('[data-answer].selected')).toHaveCount(1, {timeout:120_000});
});
