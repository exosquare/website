import { test, expect, type Page } from '@playwright/test';

// The production observer is tested by the publishing suite. Blocking it here
// lets the browser route the model fixtures instead of performing real downloads.
test.use({ serviceWorkers: 'block' });

async function imageHash(page: Page) {
  return page.locator('#mark').evaluate((element) => {
    const canvas = element as HTMLCanvasElement;
    const pixels = canvas.getContext('2d')!.getImageData(0, 0, canvas.width, canvas.height).data;
    let hash = 0;
    for (let i = 0; i < pixels.length; i += 16) hash = (Math.imul(hash, 31) + pixels[i]) | 0;
    return hash;
  });
}

// Stub only inference/downloads. Capture, analyser, worklet, rendering and UI
// still run in the browser using an audio stream generated by the test.
async function prepareSpeech(page: Page, failDownload = false) {
  let finishDownload!: () => void;
  const download = new Promise<void>((resolve) => { finishDownload = resolve; });
  await page.context().route('**/*', (route) => new URL(route.request().url()).hostname === '127.0.0.1' ? route.fallback() : route.abort());
  await page.context().route('**/test-model-load', async (route) => {
    await download;
    await route.fulfill({ status: failDownload ? 503 : 200, body: 'model fixture' });
  });
  await page.context().route('**/speech-worker.js', (route) => route.fulfill({
    contentType: 'text/javascript',
    body: `
      let listening = false;
      let sent = false;
      self.onmessage = async ({ data }) => {
        if (data.type === 'load') {
          postMessage({ type: 'progress', progress: { file: 'model.onnx', loaded: 50, total: 100 } });
          const response = await fetch('./test-model-load');
          postMessage(response.ok ? { type: 'ready' } : { type: 'error', message: 'Download interrupted' });
        }
        if (data.type === 'listen') { listening = data.on; sent = false; }
        if (data.type === 'audio' && listening && !sent) {
          sent = true;
          postMessage({ type: 'vad', probability: 0.9, active: true });
          postMessage({ type: 'output', text: 'A square, moved by sound.', start: Date.now() });
        }
      };`,
  }));
  await page.addInitScript(() => {
    const audioTest = { calls: 0, deny: false, tracks: [] as MediaStreamTrack[] };
    (window as any).__audioTest = audioTest;
    Object.defineProperty(navigator.mediaDevices, 'getUserMedia', {
      value: async () => {
        audioTest.calls++;
        if (audioTest.deny) throw new DOMException('Permission denied', 'NotAllowedError');
        const context = new AudioContext();
        await context.resume();
        const oscillator = context.createOscillator();
        oscillator.frequency.value = 160;
        const gain = context.createGain();
        gain.gain.value = 0.08;
        const destination = context.createMediaStreamDestination();
        oscillator.connect(gain).connect(destination);
        oscillator.start();
        destination.stream.getTracks().forEach((track) => {
          audioTest.tracks.push(track);
          const stop = track.stop.bind(track);
          track.stop = () => { stop(); oscillator.stop(); void context.close(); };
        });
        return destination.stream;
      },
    });
  });
  return finishDownload;
}

async function loadModel(page: Page, finishDownload: () => void) {
  const action = page.getByRole('button');
  await expect(action).toHaveCount(1);
  await expect(action).toHaveText('Download Model');
  await action.click();
  await expect(action).toBeDisabled();
  await expect(page.getByRole('progressbar')).toHaveJSProperty('value', 50);
  expect(await page.evaluate(() => (window as any).__audioTest.calls)).toBe(0);
  finishDownload();
  await expect(action).toHaveText('Start');
  await expect(action).toBeEnabled();
  expect(await page.evaluate(() => (window as any).__audioTest.calls)).toBe(0);
}

test('one action downloads, starts and stops; the transcript stays beside the block', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  const finishDownload = await prepareSpeech(page);
  const errors: string[] = [];
  const outsideRequests: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('request', (request) => {
    if (!request.url().startsWith('http://127.0.0.1:4175/')) outsideRequests.push(request.url());
  });
  await page.goto('experiments/moonshine-stt/');
  await expect.poll(() => imageHash(page)).not.toBe(0);
  const resting = await imageHash(page);
  const canvasBox = await page.locator('#mark').boundingBox();
  const transcriptBox = await page.locator('.transcript-pane').boundingBox();
  if (testInfo.project.name === 'desktop') expect(transcriptBox!.x).toBeGreaterThan(canvasBox!.x + canvasBox!.width - 1);
  else expect(transcriptBox!.y).toBeGreaterThanOrEqual(canvasBox!.y + canvasBox!.height - 1);
  await loadModel(page, finishDownload);
  const action = page.getByRole('button');
  await action.click();
  await expect(action).toHaveText('Stop');
  await expect(page.getByRole('log')).toContainText('A square, moved by sound.');
  await expect.poll(() => imageHash(page)).not.toBe(resting);
  await action.click();
  await expect(action).toHaveText('Start');
  await expect(page.getByRole('log')).toContainText('A square, moved by sound.');
  await expect.poll(() => imageHash(page)).toBe(resting);
  expect(await page.evaluate(() => (window as any).__audioTest.tracks.every((track: MediaStreamTrack) => track.readyState === 'ended'))).toBe(true);
  await action.click();
  await expect(action).toHaveText('Stop');
  await expect(page.locator('#transcript p')).toHaveCount(2);
  await action.click();
  await expect(action).toHaveText('Start');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  expect(outsideRequests).toEqual([]);
});

test('permission denial keeps Start available and allows another attempt', async ({ page }) => {
  const finishDownload = await prepareSpeech(page);
  await page.goto('experiments/moonshine-stt/');
  await loadModel(page, finishDownload);
  await page.evaluate(() => { (window as any).__audioTest.deny = true; });
  await page.getByRole('button').click();
  await expect(page.getByRole('alert')).toContainText('Microphone access was denied');
  await expect(page.getByRole('button')).toHaveText('Start');
  await expect(page.getByRole('button')).toBeEnabled();
  await page.evaluate(() => { (window as any).__audioTest.deny = false; });
  await page.getByRole('button').click();
  await expect(page.getByRole('button')).toHaveText('Stop');
  await expect(page.getByRole('alert')).toBeHidden();
  await page.getByRole('button').click();
  await expect(page.getByRole('button')).toHaveText('Start');
});

test('download failure uses the same action to retry without requesting the microphone', async ({ page }) => {
  const finishDownload = await prepareSpeech(page, true);
  await page.goto('experiments/moonshine-stt/');
  await page.getByRole('button').click();
  finishDownload();
  await expect(page.getByRole('button')).toHaveText('Retry download');
  await expect(page.getByRole('button')).toBeEnabled();
  await expect(page.getByRole('alert')).toContainText('Download interrupted');
  expect(await page.evaluate(() => (window as any).__audioTest.calls)).toBe(0);
});

test('reduced motion keeps the block still while transcription continues', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const finishDownload = await prepareSpeech(page);
  await page.goto('experiments/moonshine-stt/');
  await expect.poll(() => imageHash(page)).not.toBe(0);
  const resting = await imageHash(page);
  await loadModel(page, finishDownload);
  await page.getByRole('button').click();
  await expect(page.getByRole('log')).toContainText('A square, moved by sound.');
  expect(await imageHash(page)).toBe(resting);
  await page.getByRole('button').click();
  await expect(page.getByRole('button')).toHaveText('Start');
});
